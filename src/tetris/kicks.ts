export function wallKicks(id: PieceId, from: Rot, to: Rot): Cell[] {
  if (id === 'O') {
    return [{ x: 0, y: 0 }]
  }
  const extra = (id === 'I' ? I_KICKS : JLSTZ)[`${from}-${to}`] ?? []
  return [{ x: 0, y: 0 }, ...extra]
}
